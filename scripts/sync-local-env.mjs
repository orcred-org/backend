/**
 * Write Supabase local credentials into backend/.env.local and frontend/.env.local.
 * Preserves non-Supabase vars already in backend/.env.local when present.
 *
 * Usage (from backend/):  npm run db:env
 */
import { execSync } from "child_process";
import { readFileSync, writeFileSync, existsSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const backendRoot = join(__dirname, "..");
const frontendRoot = join(backendRoot, "..", "frontend");

function stripQuotes(value) {
  const v = value.trim();
  if (
    (v.startsWith('"') && v.endsWith('"'))
    || (v.startsWith("'") && v.endsWith("'"))
  ) {
    return v.slice(1, -1);
  }
  return v;
}

function parseEnv(text) {
  const out = {};
  for (const line of text.split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#") || trimmed.startsWith("{")) continue;
    const m = trimmed.match(/^([^=]+)=(.*)$/);
    if (m) out[m[1].trim()] = stripQuotes(m[2]);
  }
  return out;
}

function readEnvFile(path) {
  if (!existsSync(path)) return {};
  return parseEnv(readFileSync(path, "utf8"));
}

function serializeEnv(vars, header) {
  const lines = [header, ""];
  for (const [key, value] of Object.entries(vars)) {
    lines.push(`${key}=${value}`);
  }
  lines.push("");
  return lines.join("\n");
}

let statusOut;
try {
  statusOut = execSync("npx supabase status -o env", {
    cwd: backendRoot,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
  });
} catch (e) {
  console.error(
    "Could not read local Supabase status. Is Docker running?\n" +
      "  npm run db:start\n\n" +
      String(e.stderr ?? e.message),
  );
  process.exit(1);
}

const status = parseEnv(statusOut);
const apiUrl = status.API_URL ?? status.SUPABASE_URL;
const anonKey = status.ANON_KEY ?? status.SUPABASE_ANON_KEY;
const serviceKey = status.SERVICE_ROLE_KEY ?? status.SUPABASE_SERVICE_ROLE_KEY;

if (!apiUrl || !anonKey || !serviceKey) {
  console.error("Unexpected `supabase status` output. Run `npx supabase status` manually.");
  process.exit(1);
}

const backendExisting = {
  ...readEnvFile(join(backendRoot, ".env")),
  ...readEnvFile(join(backendRoot, ".env.local")),
};

const backendLocal = {
  ...backendExisting,
  NEXT_PUBLIC_SUPABASE_URL: apiUrl,
  NEXT_PUBLIC_SUPABASE_ANON_KEY: anonKey,
  SUPABASE_SERVICE_ROLE_KEY: serviceKey,
  NEXT_PUBLIC_APP_URL: backendExisting.NEXT_PUBLIC_APP_URL ?? "http://localhost:3000",
  NEXT_PUBLIC_BACKEND_URL: backendExisting.NEXT_PUBLIC_BACKEND_URL ?? "http://localhost:3001",
  ADMIN_IP_ALLOWLIST: "",
};

if (!backendLocal.CREDENTIAL_HASH_SECRET) {
  backendLocal.CREDENTIAL_HASH_SECRET = "local-dev-credential-hash-secret";
}

const frontendLocal = {
  ...readEnvFile(join(frontendRoot, ".env")),
  ...readEnvFile(join(frontendRoot, ".env.local")),
  NEXT_PUBLIC_SUPABASE_URL: apiUrl,
  NEXT_PUBLIC_SUPABASE_ANON_KEY: anonKey,
  SUPABASE_SERVICE_ROLE_KEY: serviceKey,
  NEXT_PUBLIC_API_URL: "http://localhost:3001",
};

writeFileSync(
  join(backendRoot, ".env.local"),
  serializeEnv(
    backendLocal,
    "# Auto-generated by npm run db:env — local Supabase (127.0.0.1:54321). Do not use for production.",
  ),
);

writeFileSync(
  join(frontendRoot, ".env.local"),
  serializeEnv(
    frontendLocal,
    "# Auto-generated by npm run db:env — local Supabase. Overrides frontend/.env production keys.",
  ),
);

console.log("Wrote backend/.env.local and frontend/.env.local");
console.log(`  NEXT_PUBLIC_SUPABASE_URL=${apiUrl}`);
console.log("\nRestart backend (:3001) and frontend (:3000) dev servers.");
